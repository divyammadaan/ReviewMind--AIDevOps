"""Generate the labelled evaluation dataset by injecting catalogued defects.

Stdlib only -- deliberately. This script must run even before project dependencies
are installed, so the dataset can always be regenerated by a third party
(reproducibility criterion).

Usage:
    python3 experiments/seed_bugs.py                 # generate
    python3 experiments/seed_bugs.py --verify-only   # check injection without writing

Output:
    experiments/dataset/cases/<case_id>/before/   clean corpus snapshot
    experiments/dataset/cases/<case_id>/after/    defective corpus snapshot
    experiments/dataset/cases/<case_id>/case.json  label + unified diff
    experiments/dataset/manifest.json              index of all cases
"""

from __future__ import annotations

import argparse
import difflib
import json
import shutil
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bugs.catalog import FULL_CATALOG, SeededDefect  # noqa: E402

ROOT = Path(__file__).resolve().parent
CORPUS = ROOT / "corpus" / "taskapi"
DATASET = ROOT / "dataset"


class InjectionError(RuntimeError):
    """Raised when a defect cannot be injected unambiguously."""


def _locate_injection_span(original: str, modified: str) -> tuple[int, int]:
    """1-based inclusive line span of the injected defect, in the MODIFIED file.

    Returns (start, end).

    Why a span rather than a single line: a defect injected as a multi-line block
    manifests somewhere inside that block, not necessarily on its first line.
    `sql_injection_001` inserts a function at line 29 whose vulnerable query is at
    line 33 -- scoring against line 29 alone would mark a correct detection at line
    33 as a miss, misreporting the tool rather than the tool misreporting the bug.

    The span is derived mechanically with difflib, so it is not an author's
    judgement call. See docs/RESEARCH_DESIGN.md §6.4 for the matching rule and the
    note recording why this replaced the original single-line label.
    """
    o_lines = original.splitlines()
    m_lines = modified.splitlines()

    sm = difflib.SequenceMatcher(a=o_lines, b=m_lines, autojunk=False)
    changed: list[int] = []
    for tag, _i1, _i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        # 'replace'/'insert' -> lines j1..j2 in the modified file.
        # 'delete' -> nothing remains in the modified file, so anchor at j1.
        changed.extend(range(j1 + 1, j2 + 1) if j2 > j1 else [j1 + 1])

    if not changed:
        anchor = min(len(o_lines), len(m_lines)) + 1
        return (anchor, anchor)
    return (min(changed), max(changed))


def inject(defect: SeededDefect) -> tuple[str, str, tuple[int, int]]:
    """Apply one defect. Returns (original_text, modified_text, injected_span).

    Raises InjectionError when `find` does not match exactly once -- we refuse to
    guess, because an ambiguous match would produce a mislabelled case.
    """
    target = CORPUS / defect.target_file
    if not target.exists():
        raise InjectionError(f"{defect.case_id}: target file missing: {defect.target_file}")

    original = target.read_text()
    hits = original.count(defect.find)
    if hits == 0:
        raise InjectionError(
            f"{defect.case_id}: `find` pattern not found in {defect.target_file}. "
            "The corpus may have drifted from the catalogue."
        )
    if hits > 1:
        raise InjectionError(
            f"{defect.case_id}: `find` pattern matches {hits} times in "
            f"{defect.target_file}; it must match exactly once."
        )

    modified = original.replace(defect.find, defect.replace)
    if modified == original:
        raise InjectionError(f"{defect.case_id}: replacement produced no change.")

    return original, modified, _locate_injection_span(original, modified)


def unified_diff(defect: SeededDefect, original: str, modified: str) -> str:
    return "".join(
        difflib.unified_diff(
            original.splitlines(keepends=True),
            modified.splitlines(keepends=True),
            fromfile=f"a/{defect.target_file}",
            tofile=f"b/{defect.target_file}",
            n=3,
        )
    )


def _copy_corpus(dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(
        CORPUS, dest,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )


def build(verify_only: bool = False) -> int:
    if not CORPUS.exists():
        print(f"ERROR: corpus not found at {CORPUS}", file=sys.stderr)
        return 1

    results = []
    failures = []

    for defect in FULL_CATALOG:
        try:
            original, modified, span = inject(defect)
        except InjectionError as exc:
            failures.append(str(exc))
            continue

        diff = unified_diff(defect, original, modified)
        record = {
            **asdict(defect),
            # `injected_line` is retained as the span start for readability and
            # backwards compatibility; `injected_span` is what scoring uses.
            "injected_line": span[0],
            "injected_span": list(span),
            "diff": diff,
        }
        results.append(record)

        if verify_only:
            continue

        case_dir = DATASET / "cases" / defect.case_id
        _copy_corpus(case_dir / "before")
        _copy_corpus(case_dir / "after")
        (case_dir / "after" / defect.target_file).write_text(modified)
        (case_dir / "case.json").write_text(json.dumps(record, indent=2))

    # Report ------------------------------------------------------------------
    if failures:
        print(f"INJECTION FAILURES ({len(failures)}):", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)

    print(f"{'Verified' if verify_only else 'Generated'} {len(results)}/{len(FULL_CATALOG)} cases")

    if not verify_only and results:
        manifest = {
            "n_cases": len(results),
            "corpus": str(CORPUS.relative_to(ROOT.parent)),
            "cases": [
                {
                    "case_id": r["case_id"],
                    "defect_class": r["defect_class"],
                    "target_file": r["target_file"],
                    "injected_line": r["injected_line"],
                    "injected_span": r["injected_span"],
                    "requires_cross_file_context": r["requires_cross_file_context"],
                    "static_analysis_expected": r["static_analysis_expected"],
                    "injection_mode": r["injection_mode"],
                }
                for r in results
            ],
        }
        DATASET.mkdir(parents=True, exist_ok=True)
        (DATASET / "manifest.json").write_text(json.dumps(manifest, indent=2))
        print(f"Manifest: {DATASET / 'manifest.json'}")

    print("\nper-case ground truth:")
    for r in results:
        flag = "cross-file" if r["requires_cross_file_context"] else "local"
        a, b = r["injected_span"]
        span = f"L{a}" if a == b else f"L{a}-{b}"
        print(f"  {r['case_id']:26s} {r['target_file']:22s} {span:>9s}  "
              f"{r['injection_mode']:9s} {flag}")

    return 1 if failures else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify-only", action="store_true",
                    help="validate injection without writing the dataset")
    args = ap.parse_args()
    raise SystemExit(build(verify_only=args.verify_only))
